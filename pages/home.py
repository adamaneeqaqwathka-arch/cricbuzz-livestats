"""Streamlit home page: project overview and navigation."""

import streamlit as st

st.title("🏏 Cricbuzz LiveStats")
st.subheader("Real-time cricket insights and SQL-based analytics")

st.write(
    "This dashboard combines live data from the Cricbuzz API with a MySQL "
    "database to deliver live match updates, player statistics, SQL-driven "
    "analytics and full CRUD operations for data management."
)

st.header("Pages")

col1, col2 = st.columns(2)

with col1:
    st.page_link("pages/live_matches.py", label="Live Matches", icon="⚡")
    st.caption("Ongoing, recent and finished matches straight from the Cricbuzz API.")

    st.page_link("pages/top_stats.py", label="Top Stats", icon="📊")
    st.caption("Batting and bowling leaderboards by format, with charts.")

with col2:
    st.page_link("pages/sql_queries.py", label="SQL Queries", icon="🔍")
    st.caption("25 analytics questions answered with SQL, plus a read-only query box.")

    st.page_link("pages/crud_operations.py", label="CRUD Operations", icon="🛠")
    st.caption("Add, view, edit and delete player records with validated forms.")

st.header("Tools used")
st.write(
    "Python · Streamlit · MySQL · REST API (requests) · JSON · pandas"
)

st.header("About the data")
st.info(
    "Live matches, scorecards and the career statistics of the loaded players "
    "come from the Cricbuzz API. The large set of 132 matches used by the "
    "advanced SQL questions (head-to-head, form, quarterly trends) is "
    "**synthetic sample data** generated by `generate_sample_data.py`. It uses "
    "fictional teams named 'Sample ...' and is not real cricket data."
)

with st.expander("Project folder structure"):
    st.code(
        """cricbuzz_livestats/
├── app.py                  # Streamlit entry point and navigation
├── requirements.txt        # Python packages
├── README.md               # Setup instructions
├── pages/                  # One file per Streamlit page
├── utils/                  # API client, parsers, loaders, DB connection
├── sql/                    # Schema, seed data, data preparation, 25 queries
├── notebooks/              # Optional practice notebooks
└── data/                   # Saved API responses (cache)""",
        language="text",
    )
    st.write("See README.md in the repository for full documentation.")